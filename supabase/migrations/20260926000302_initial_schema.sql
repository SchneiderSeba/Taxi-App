create table if not exists public."UsersProfile" (
  id bigint generated by default as identity primary key,
  owner_id uuid not null unique references auth.users(id) on delete cascade,
  username text not null,
  "displayName" text,
  email text not null unique,
  phone numeric,
  "carModel" text not null,
  "carPlate" text not null unique,
  "pictureUrl" text,
  available boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public."Trips" (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  customer_id text,
  name text not null,
  address text,
  pickup text,
  destination text,
  passenger_phone text,
  preferred_time text,
  price numeric(12, 2) check (price is null or price >= 0),
  done text not null default 'pending' check (done in ('pending', 'completed', 'cancelled')),
  done_by_customer boolean,
  created_at timestamptz not null default now()
);

create index if not exists trips_owner_id_idx on public."Trips" (owner_id);
create index if not exists trips_customer_id_created_at_idx on public."Trips" (customer_id, created_at desc);

create table if not exists public."Expenses" (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  type text not null,
  amount numeric(12, 2) not null check (amount >= 0),
  date date not null default current_date,
  created_at timestamp without time zone default (now() at time zone 'utc')
);

create index if not exists expenses_owner_id_idx on public."Expenses" (owner_id);

create table if not exists public.usersettings (
  id bigint generated by default as identity primary key,
  owner_id uuid not null unique references auth.users(id) on delete cascade,
  gas_unit_cost numeric default 50,
  insurance_monthly numeric default 100,
  registration_monthly numeric default 50,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  trip_id bigint references public."Trips"(id) on delete set null,
  owner_id uuid references public."UsersProfile"(owner_id) on delete set null,
  customer_id text,
  client_id uuid default auth.uid(),
  topic text,
  mp_payment_id text not null unique,
  amount numeric(12, 2),
  status text,
  raw_query jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists payments_owner_id_idx on public.payments (owner_id);
create index if not exists payments_trip_id_idx on public.payments (trip_id);

