create or replace function public.list_available_drivers()
returns table (
  id bigint,
  owner_id uuid,
  username text,
  "displayName" text,
  "carModel" text,
  "carPlate" text,
  "pictureUrl" text,
  available boolean,
  created_at timestamptz
)
language sql
security definer
set search_path = ''
stable
as $$
  select p.id, p.owner_id, p.username, p."displayName", p."carModel", p."carPlate",
         p."pictureUrl", coalesce(p.available, false), p.created_at
  from public."UsersProfile" p
  where coalesce(p.available, false) = true
  order by p.created_at desc;
$$;

create or replace function public.request_trip(
  p_customer_id text,
  p_owner_id uuid,
  p_name text,
  p_pickup text,
  p_destination text,
  p_passenger_phone text default null,
  p_preferred_time text default null
)
returns table (trip_id bigint, created_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  inserted_trip public."Trips";
begin
  if length(trim(p_customer_id)) < 32 then
    raise exception 'Invalid customer identifier';
  end if;
  if nullif(trim(p_name), '') is null or nullif(trim(p_pickup), '') is null or nullif(trim(p_destination), '') is null then
    raise exception 'Name, pickup and destination are required';
  end if;
  if not exists (
    select 1 from public."UsersProfile"
    where owner_id = p_owner_id and available = true
  ) then
    raise exception 'Driver is not available';
  end if;

  insert into public."Trips" (
    owner_id, customer_id, name, pickup, destination, passenger_phone, preferred_time, done
  ) values (
    p_owner_id, p_customer_id, trim(p_name), trim(p_pickup), trim(p_destination),
    nullif(trim(p_passenger_phone), ''), nullif(trim(p_preferred_time), ''), 'pending'
  ) returning * into inserted_trip;

  return query select inserted_trip.id, inserted_trip.created_at;
end;
$$;

create or replace function public.get_customer_last_trip(p_customer_id text)
returns table (
  trip_id bigint,
  done text,
  created_at timestamptz,
  owner_id uuid,
  pickup text,
  destination text,
  preferred_time text,
  price numeric,
  driver_name text,
  driver_available boolean
)
language sql
security definer
set search_path = public
stable
as $$
  select t.id, t.done, t.created_at, t.owner_id, t.pickup, t.destination,
         t.preferred_time, t.price,
         coalesce(p."displayName", p.username, 'Conductor') as driver_name,
         p.available as driver_available
  from public."Trips" t
  join public."UsersProfile" p on p.owner_id = t.owner_id
  where t.customer_id = p_customer_id and length(trim(p_customer_id)) >= 32
  order by t.created_at desc
  limit 1;
$$;

create or replace function public.get_payment_result(p_payment_id text)
returns table (amount numeric, status text, mp_payment_id text)
language sql
security definer
set search_path = public
stable
as $$
  select p.amount, p.status, p.mp_payment_id
  from public.payments p
  where p.mp_payment_id = p_payment_id
  limit 1;
$$;

